-- =============================================================================
-- ThermoCity — Épico 83 · tabelas da busca ativa (Oracle 19c+)
-- Pré-requisito: sql/01_criar_tabelas.sql (TMC_SETOR, TMC_SERVICO, TMC_PESSOA_SINTETICA...).
--
-- Lista do dia por UBS -> itens (uma pessoa por item, com pontuação e motivo)
-- -> contatos registrados pelo agente. Auditoria LGPD das alterações de pessoas.
-- =============================================================================

-- Lista de busca ativa de um dia para uma UBS.
CREATE TABLE TMC_LISTA_BUSCA (
    ID_LISTA       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DATA_LOCAL     DATE           NOT NULL,
    UBS_ID         VARCHAR2(40)   NOT NULL,
    NIVEL          NUMBER(1)      NOT NULL,
    STATUS         VARCHAR2(10)   DEFAULT 'ABERTA' NOT NULL,
    VERSAO_REGRA   VARCHAR2(10)   DEFAULT 'v1' NOT NULL,
    GERADA_EM      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ENCERRADA_EM   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_TMC_LISTA_BUSCA PRIMARY KEY (ID_LISTA),
    CONSTRAINT UK_TMC_LISTA_DIA_UBS UNIQUE (DATA_LOCAL, UBS_ID),
    CONSTRAINT FK_TMC_LISTA_UBS FOREIGN KEY (UBS_ID) REFERENCES TMC_SERVICO (ID),
    CONSTRAINT CK_TMC_LISTA_NIVEL CHECK (NIVEL BETWEEN 1 AND 5),
    CONSTRAINT CK_TMC_LISTA_STATUS CHECK (STATUS IN ('ABERTA','ENCERRADA'))
);

COMMENT ON TABLE TMC_LISTA_BUSCA IS 'Lista de busca ativa de um dia para uma UBS, gerada por PKG_PRIORIZACAO.PRC_GERAR_LISTA_DIA';

-- Pessoa dentro de uma lista, com a posição, a pontuação e o motivo (regra explicável).
CREATE TABLE TMC_ITEM_LISTA (
    ID_ITEM        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_LISTA       NUMBER         NOT NULL,
    PESSOA_ID      NUMBER(19)     NOT NULL,
    POSICAO        NUMBER(6),
    PONTUACAO      NUMBER(2)      NOT NULL,
    MOTIVO         VARCHAR2(400),
    STATUS         VARCHAR2(20)   DEFAULT 'PENDENTE' NOT NULL,
    ATUALIZADO_EM  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TMC_ITEM_LISTA PRIMARY KEY (ID_ITEM),
    CONSTRAINT UK_TMC_ITEM_LISTA_PESSOA UNIQUE (ID_LISTA, PESSOA_ID),
    CONSTRAINT FK_TMC_ITEM_LISTA FOREIGN KEY (ID_LISTA) REFERENCES TMC_LISTA_BUSCA (ID_LISTA) ON DELETE CASCADE,
    CONSTRAINT FK_TMC_ITEM_PESSOA FOREIGN KEY (PESSOA_ID) REFERENCES TMC_PESSOA_SINTETICA (ID) ON DELETE CASCADE,
    CONSTRAINT CK_TMC_ITEM_PONTUACAO CHECK (PONTUACAO BETWEEN 0 AND 16),
    CONSTRAINT CK_TMC_ITEM_STATUS CHECK (STATUS IN ('PENDENTE','CONTATADO_BEM','PRECISA_AJUDA','NAO_ATENDEU','DADOS_INCORRETOS'))
);

CREATE INDEX IX_TMC_ITEM_PESSOA ON TMC_ITEM_LISTA (PESSOA_ID);
COMMENT ON TABLE TMC_ITEM_LISTA IS 'Pessoa na lista do dia. STATUS e atualizado pelo gatilho TRG_TMC_CONTATO_ATUALIZA_ITEM';
COMMENT ON COLUMN TMC_ITEM_LISTA.MOTIVO IS 'Por que a pessoa esta na lista (regra v1 explicavel)';

-- Contato feito pelo agente de saúde.
CREATE TABLE TMC_CONTATO (
    ID_CONTATO      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PESSOA_ID       NUMBER(19)     NOT NULL,
    ID_ITEM         NUMBER,
    RESULTADO       VARCHAR2(20)   NOT NULL,
    OBSERVACAO      VARCHAR2(1000),
    REGISTRADO_POR  VARCHAR2(128)  NOT NULL,
    REGISTRADO_EM   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TMC_CONTATO PRIMARY KEY (ID_CONTATO),
    CONSTRAINT FK_TMC_CONTATO_PESSOA FOREIGN KEY (PESSOA_ID) REFERENCES TMC_PESSOA_SINTETICA (ID) ON DELETE CASCADE,
    CONSTRAINT FK_TMC_CONTATO_ITEM FOREIGN KEY (ID_ITEM) REFERENCES TMC_ITEM_LISTA (ID_ITEM) ON DELETE SET NULL,
    CONSTRAINT CK_TMC_CONTATO_RESULTADO CHECK (RESULTADO IN ('CONTATADO_BEM','PRECISA_AJUDA','NAO_ATENDEU','DADOS_INCORRETOS'))
);

CREATE INDEX IX_TMC_CONTATO_PESSOA ON TMC_CONTATO (PESSOA_ID);
CREATE INDEX IX_TMC_CONTATO_ITEM ON TMC_CONTATO (ID_ITEM);
COMMENT ON TABLE TMC_CONTATO IS 'Contatos da busca ativa, gravados por PKG_CONTATO.PRC_REGISTRAR_CONTATO';

-- Trilha de auditoria LGPD das pessoas acompanhadas (sem FK: a linha fica mesmo depois da exclusão).
CREATE TABLE TMC_AUDITORIA_PESSOA (
    ID_AUDITORIA     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PESSOA_ID        NUMBER(19)     NOT NULL,
    OPERACAO         VARCHAR2(6)    NOT NULL,
    USUARIO          VARCHAR2(128)  NOT NULL,
    DATA_HORA        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    VALORES_ANTIGOS  VARCHAR2(4000),
    VALORES_NOVOS    VARCHAR2(4000),
    CONSTRAINT PK_TMC_AUDITORIA_PESSOA PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT CK_TMC_AUDITORIA_OPERACAO CHECK (OPERACAO IN ('INSERT','UPDATE','DELETE'))
);

CREATE INDEX IX_TMC_AUDITORIA_PESSOA ON TMC_AUDITORIA_PESSOA (PESSOA_ID);
COMMENT ON TABLE TMC_AUDITORIA_PESSOA IS 'Trilha LGPD: quem alterou, quando, operacao e valores antigo/novo de TMC_PESSOA_SINTETICA';
